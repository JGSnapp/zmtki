const EMBEDDED_PAGE = `# Карточки с разметкой: html, ui, вебвью

Задача: карточка должна выглядеть как часть доски, а не как кусок веб-страницы,
вставленный в рамку. Два признака, что что-то не так, — полоса прокрутки внутри
карточки и светлые поля по краям.

## Откуда берутся поля и ползунки

Карточка \`html\` и \`ui\` — это документ в песочнице. Если отдать фрагмент без
своей страницы, вокруг него окажется страница по умолчанию: \`body\` с отступом
8px и белым фоном. Отступ и есть светлая рамка по краям, и он же выталкивает
содержимое высотой 100% за пределы окна — отсюда ползунок.

Доска подставляет фрагменту свою страницу: нулевые отступы, прозрачный фон,
скрытые полосы прокрутки. Полагаться на это не нужно — пиши так, чтобы карточка
была правильной и сама по себе.

## Правила

1. Отдавай либо цельный документ с \`<!doctype html>\`, либо фрагмент, который
   сам занимает всю карточку. Цельный документ доска не трогает — весь сброс в
   нём твой: \`html,body{margin:0;padding:0;height:100%}\`.
2. Корневой элемент фрагмента — \`width:100%;height:100%\` и обязательно
   \`box-sizing:border-box\`, иначе \`padding\` прибавится к 100% и снова появится
   прокрутка.
3. Не рассчитывай на белую страницу: доска тёмная, и подложка карточки тёмная.
   Задавай фон и цвет текста явно — либо свои, либо никаких, но не «как получится».
4. Подбирай размер карточки под содержимое, а не содержимое под карточку.
   Не влезает — увеличивай width/height в artifact_create, а не уменьшай текст.
5. Прокрутка внутри карточки — крайний случай. Длинный материал разбивай на
   несколько карточек: доска для того и бесконечная.
6. Скрипты в песочнице работают, но страница изолирована: ни хранилища, ни
   доступа к доске. Нужна логика поверх доски — это агент и MCP, а не карточка.
7. Вебвью и вкладка браузера — живой сайт, его оформление тебе не принадлежит.
   Раскладку доска берёт на себя: страница всегда получает настольное окно
   шириной 1280px, а результат ужимается под карточку. Поэтому узкая карточка
   не ломает сайт — она просто показывает его мелко, и пользователь приближает
   доску, чтобы прочитать. Размер выбирай по тому, сколько нужно видеть сразу:
   для беглого взгляда хватит 400x300, для чтения бери от 900x600.

## Быстрая проверка

Прежде чем создавать карточку, посмотри на разметку и ответь:
- есть ли у корня \`height:100%\` и \`box-sizing:border-box\`;
- задан ли фон и цвет текста;
- поместится ли содержимое в заданные width/height без прокрутки.
`;

